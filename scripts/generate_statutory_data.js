const fs = require('fs');
const path = require('path');

// We will extract data from the 3 seed files by reading and parsing their arrays
const seed1Path = path.join(__dirname, 'seed_constitution_and_rules.ts');
const seed2Path = path.join(__dirname, 'seed_extended_constitution.ts');
const seed3Path = path.join(__dirname, 'seed_ppc_and_statutes.ts');

const content1 = fs.readFileSync(seed1Path, 'utf8');
const content2 = fs.readFileSync(seed2Path, 'utf8');
const content3 = fs.readFileSync(seed3Path, 'utf8');

// Helper to extract exported array content between const NAME = [ ... ];
function extractArray(content, varName) {
  const startRegex = new RegExp(`const\\s+${varName}[^=]*=\\s*\\[`);
  const match = content.match(startRegex);
  if (!match) return [];
  const startIndex = match.index + match[0].length - 1;
  
  // Find matching bracket
  let depth = 0;
  let inString = false;
  let strChar = '';
  let escape = false;
  let endIndex = -1;

  for (let i = startIndex; i < content.length; i++) {
    const char = content[i];
    if (escape) {
      escape = false;
      continue;
    }
    if (char === '\\') {
      escape = true;
      continue;
    }
    if (inString) {
      if (char === strChar) {
        inString = false;
      }
      continue;
    }
    if (char === "'" || char === '"' || char === '`') {
      inString = true;
      strChar = char;
      continue;
    }
    if (char === '[') depth++;
    if (char === ']') {
      depth--;
      if (depth === 0) {
        endIndex = i;
        break;
      }
    }
  }

  if (endIndex === -1) return [];
  const arrayCode = content.substring(startIndex, endIndex + 1);
  return arrayCode;
}

const articles1Code = extractArray(content1, 'CONSTITUTIONAL_ARTICLES');
const rules1Code = extractArray(content1, 'STATUTORY_RULES');
const articles2Code = extractArray(content2, 'EXTENDED_ARTICLES');
const rules3Code = extractArray(content3, 'PPC_AND_STATUTORY_PROVISIONS');

const outputTs = `// AUTOGENERATED STATUTORY REPOSITORY FOR PAKISTANI CONSTITUTION & STATUTORY RULES
// Serves as high-performance local database grounding and infallible zero-downtime fallback.

import { ConstitutionalArticleResult, StatutoryRuleResult } from './retrieval';

const RAW_ARTICLES_1 = ${articles1Code};
const RAW_ARTICLES_2 = ${articles2Code};
const RAW_RULES_1 = ${rules1Code};
const RAW_RULES_3 = ${rules3Code};

export const FALLBACK_CONSTITUTIONAL_ARTICLES: ConstitutionalArticleResult[] = [
  ...RAW_ARTICLES_1,
  ...RAW_ARTICLES_2,
].map((item: any, idx: number) => ({
  id: \`fallback-art-\${idx + 1}\`,
  articleNumber: item.articleNumber,
  title: item.title,
  part: item.part,
  chapter: item.chapter || null,
  content: item.content,
  explanation: item.explanation || null,
  keyTopics: item.keyTopics || [],
  crossReferences: item.crossReferences || [],
  amendmentNotes: item.amendmentNotes || null,
}));

export const FALLBACK_STATUTORY_RULES: StatutoryRuleResult[] = [
  ...RAW_RULES_1,
  ...RAW_RULES_3,
].map((item: any, idx: number) => ({
  id: \`fallback-rule-\${idx + 1}\`,
  statuteCode: item.statuteCode,
  statuteName: item.statuteName,
  ruleNumber: item.ruleNumber,
  title: item.title,
  category: item.category,
  content: item.content,
  courtType: item.courtType || null,
  notes: item.notes || null,
  keyTopics: item.keyTopics || [],
  crossReferences: item.crossReferences || [],
}));
`;

const outputPath = path.join(__dirname, '..', 'lib', 'constitution', 'statutoryData.ts');
fs.writeFileSync(outputPath, outputTs, 'utf8');
console.log(`Successfully generated statutoryData.ts with ${articles1Code.length} bytes of articles and rules at ${outputPath}`);
